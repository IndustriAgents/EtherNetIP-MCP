from __future__ import annotations

from typing import Any, Protocol


class EIPClientPort(Protocol):
    config: Any

    def backend(self) -> Any: ...

    def shutdown(self) -> Any: ...

    def closing(self) -> Any: ...

    async def ensure_connection(self) -> Any: ...

    async def close(self) -> Any: ...

    async def read_tag(self, tag: Any, count: Any = ...) -> Any: ...

    async def read_multiple_tags(self, tags: Any) -> Any: ...

    async def get_tag_list(self, program: Any = ...) -> Any: ...

    async def get_controller_info(self) -> Any: ...

    async def get_plc_time(self) -> Any: ...

    async def ping(self) -> Any: ...

    async def write_tag(self, tag: Any, value: Any, data_type: Any = ...) -> Any: ...

    async def write_multiple_tags(self, items: Any) -> Any: ...

    async def set_plc_time(self) -> Any: ...

    def connection_status(self) -> Any: ...

    def call_deadline(self) -> Any: ...
